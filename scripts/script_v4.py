SECTIONS, SHOTS = [], []
_bgm = "none"


def sec(name, bgm):
    global _bgm
    SECTIONS.append(name)
    _bgm = bgm


_NUM = [0]


def shot(who, line, pic):
    _NUM[0] += 1  # ids stay stable: inserted vox() clips don't renumber later shots (studio takes are keyed by id)
    SHOTS.append({"id": f"{_NUM[0]:03d}", "sec": SECTIONS[-1], "who": who, "line": line, "pic": pic, "bgm": _bgm})


def ins(who, line, pic):
    """New narration shot inserted after the current one, id = previous base id + n<k> (no renumbering)."""
    base = SHOTS[-1]["id"].split("v")[0].split("n")[0]
    k = sum(1 for x in SHOTS if x["id"].startswith(base + "n")) + 1
    SHOTS.append({"id": f"{base}n{k}", "sec": SECTIONS[-1], "who": who, "line": line, "pic": pic, "bgm": _bgm})


def vox(line, pic):
    """Modern voice (interview / visitor / lecture) with its ORIGINAL sound: pic = "fc:FILE:A:B". id = previous id + v<n>."""
    base = SHOTS[-1]["id"].split("v")[0]
    n = sum(1 for x in SHOTS if x["id"].startswith(base + "v")) + 1
    SHOTS.append({"id": f"{base}v{n}", "sec": SECTIONS[-1], "who": "无", "line": line, "pic": pic, "bgm": _bgm})


