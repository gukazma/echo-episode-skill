def sec(name, bgm, ctx="calm"):
    global _bgm, _ctx
    SECTIONS.append(name)
    if bgm != _bgm:  # same piece across a section break keeps playing
        _NEW[0] = True
    _bgm, _ctx = bgm, ctx


def bgm(key):
    """music cue inside a section (a new bed starts at the next shot, even if it is the same piece again)"""
    global _bgm
    _bgm = key
    _NEW[0] = True


def F(key, t="auto"):
    return f"f:footage/{key}.mp4:{t}"


def O(key, a, b):
    return f"fc:footage/{key}.mp4:{a}:{b}"


def shot(who, line, pic, sub="", **kw):
    if not sub:  # sub="b": an extra shot right after the previous one, ids of all later shots stay unchanged
        _NUM[0] += 1
    ctx = kw.pop("ctx", None) or (CTX["xy"] if who == XY else CTX[_ctx])
    if ctx in SLOW and who != NO:
        kw.setdefault("rate", SLOW[ctx])
        kw.setdefault("maxpause", 0.9)  # 11-17: 1.4 s 的句中停顿听着拖沓
        kw.setdefault("pad", 1.2)  # 情绪句说完，画面多停一会
    if _NEW[0]:
        kw["newbed"] = True
        _NEW[0] = False
    SHOTS.append({"id": f"{_NUM[0]:03d}{sub}", "sec": SECTIONS[-1], "who": who, "line": line, "pic": pic, "bgm": _bgm, "ctx": ctx, **kw})


def breath(key, t, hold, amb=0.6, cap="", **kw):
    """留白：旁白停下，原片 key@t 带现场声放 hold 秒，音乐推上来（amb = 现场声音量，0 = 只听音乐）"""
    shot(NO, "", F(key, t), hold=hold, breath=amb, cap=cap, **kw)


